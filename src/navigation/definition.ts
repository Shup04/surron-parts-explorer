/**
 * Public navigation is a presentation layer over immutable source occurrences.
 * These explicit roles organize physical components; membership does not establish
 * fitment, interchangeability, mechanical containment, or the installed variant.
 * OEM identities and source quantities remain separate in the reference catalog.
 * Packaged whole-assembly alternatives remain in assembly reference details rather
 * than becoming additional installed children alongside their constituent parts.
 */
export interface NavigationDefinition {
  id: string;
  name: string;
  kind: 'component' | 'group' | 'service';
  oemNumbers?: string[];
  sourceRowIds?: string[];
  /** Restrict matching occurrences to these source assembly groups. */
  sourceAssemblyIds?: string[];
  children?: NavigationDefinition[];
}

export interface SystemDefinition {
  /** Existing catalog assembly identity, retained for navigation and deep links. */
  id: string;
  name: string;
  sourceAssemblyIds: string[];
  children: NavigationDefinition[];
}

